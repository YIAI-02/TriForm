def _validate_business_id(business_id: int) -> None:
    if business_id not in DISTS:
        raise ValueError(f"business_id must be in 1..13, got {business_id}")


def _sample_index(weights: List[int], rng: random.Random) -> int:
    """Sample an index i with probability proportional to weights[i]."""
    total = sum(w for w in weights if w > 0)
    if total <= 0:
        # Fallback: uniform over indices
        return rng.randrange(len(weights))

    r = rng.random() * total
    acc = 0
    # Linear scan is fine here (arrays are ~150 long).
    for i, w in enumerate(weights):
        if w <= 0:
            continue
        acc += w
        if r <= acc:
            return i
    return len(weights) - 1


def _index_to_value(i: int, n: int, x_min: float, x_max: float, rng: random.Random) -> int:
    """Convert sampled index i to an integer token length, uniformly within its x-interval."""
    if n <= 0:
        return int(round(x_min))
    span = x_max - x_min
    lo = x_min + (i / n) * span
    hi = x_min + ((i + 1) / n) * span
    v = rng.uniform(lo, hi)
    iv = int(round(v))
    if iv < x_min:
        iv = int(x_min)
    if iv > x_max:
        iv = int(x_max)
    return iv


def _sample_pair_with_rng(business_id: int, rng: random.Random) -> Tuple[int, int]:
    pre = DISTS[business_id]["prefill"]
    dec = DISTS[business_id]["decode"]

    pre_weights: List[int] = pre["weights"]  # type: ignore[assignment]
    dec_weights: List[int] = dec["weights"]  # type: ignore[assignment]

    pre_i = _sample_index(pre_weights, rng)
    dec_i = _sample_index(dec_weights, rng)

    pre_len = _index_to_value(pre_i, len(pre_weights), float(pre["min"]), float(pre["max"]), rng)
    dec_len = _index_to_value(dec_i, len(dec_weights), float(dec["min"]), float(dec["max"]), rng)

    return pre_len, dec_len


def sample_pair(business_id: int, seed: Optional[int] = None) -> Tuple[int, int]:
    """Sample one (prefill_length, decode_length) pair for the given business_id."""
    _validate_business_id(business_id)
    rng = random.Random(seed)
    return _sample_pair_with_rng(business_id, rng)


def sample_n(business_id: int, n: int, seed: Optional[int] = None) -> List[Tuple[int, int]]:
    """Sample n pairs."""
    _validate_business_id(business_id)
    if n <= 0:
        return []
    rng = random.Random(seed)
    return [_sample_pair_with_rng(business_id, rng) for _ in range(n)]


def main() -> None:
    parser = argparse.ArgumentParser(description="Sample prefill/decode token lengths by business id.")
    parser.add_argument("business_id", type=int, help="Business id (1..13)")
    parser.add_argument("--seed", type=int, default=None, help="Random seed (optional)")
    parser.add_argument("-n", "--num", type=int, default=1, help="Number of samples to generate")
    args = parser.parse_args()

    if args.num <= 1:
        pre, dec = sample_pair(args.business_id, seed=args.seed)
        print(f"business {args.business_id}: prefill={pre}, decode={dec}")
    else:
        pairs = sample_n(args.business_id, args.num, seed=args.seed)
        for idx, (pre, dec) in enumerate(pairs, start=1):
            print(f"{idx}: business {args.business_id}: prefill={pre}, decode={dec}")


if __name__ == "__main__":
    main()
