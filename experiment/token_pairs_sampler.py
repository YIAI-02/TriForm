def _weighted_choice(weights: List[int], rng: random.Random) -> int:
    total = sum(weights)
    if total <= 0:
        return rng.randrange(len(weights))
    r = rng.random() * total
    acc = 0.0
    for i, w in enumerate(weights):
        if w <= 0:
            continue
        acc += w
        if r < acc:
            return i
    return len(weights) - 1

@dataclass(frozen=True)
class PixelHistogram:
    min_val: float
    max_val: float
    counts: List[int]
    red_x: int
    blue_x: int

    def _step(self) -> float:
        w = len(self.counts)
        return (self.max_val - self.min_val) / (w - 1)

    def x_to_val(self, x: int) -> float:
        w = len(self.counts)
        return self.min_val + (x / (w - 1)) * (self.max_val - self.min_val)

    @property
    def p95(self) -> float:
        return self.x_to_val(self.red_x)

    @property
    def p99(self) -> float:
        return self.x_to_val(self.blue_x)

    def sample(self, rng: Optional[random.Random] = None) -> int:
        rng = rng or random.Random()
        step = self._step()

        u = rng.random()
        if u < 0.95:
            # <= P95
            x = _weighted_choice(self.counts[: self.red_x + 1], rng)
            val = self.min_val + x * step + rng.random() * step
        elif u < 0.99:
            # (P95, P99]
            seg = self.counts[self.red_x + 1 : self.blue_x + 1]
            if sum(seg) <= 0:
                val = rng.uniform(self.p95, self.p99)
            else:
                x_local = _weighted_choice(seg, rng)
                x = (self.red_x + 1) + x_local
                val = self.min_val + x * step + rng.random() * step
        else:
            if self.max_val <= self.p99:
                val = self.p99
            else:
                val = rng.uniform(self.p99, self.max_val)

        out = int(round(val))
        if out < int(self.min_val):
            out = int(self.min_val)
        if out > int(self.max_val):
            out = int(self.max_val)
        return out


