def sample_four_pairs(seed: Optional[int] = None) -> Dict[str, Tuple[int, int]]:
    rng = random.Random(seed)
    out: Dict[str, Tuple[int, int]] = {}
    for bname, hists in BUSINESS_HISTS.items():
        inp = hists["input"].sample(rng)
        outp = hists["output"].sample(rng)
        out[bname] = (inp, outp)
    return out


def sample_many(n: int, seed: Optional[int] = None) -> List[Dict[str, Tuple[int, int]]]:
    rng = random.Random(seed)
    return [
        {b: (h["input"].sample(rng), h["output"].sample(rng)) for b, h in BUSINESS_HISTS.items()}
        for _ in range(n)
    ]


